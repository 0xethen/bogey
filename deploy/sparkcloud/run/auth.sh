#!/bin/bash
. /srv/bogey/run/common.sh
wait_db
export GOTRUE_DB_MIGRATIONS_PATH=/srv/img/auth/usr/local/etc/auth/migrations
export GOTRUE_API_HOST=127.0.0.1 GOTRUE_API_PORT=9999 API_EXTERNAL_URL
export GOTRUE_DB_DRIVER=postgres GOTRUE_DB_DATABASE_URL=postgres://supabase_auth_admin:$POSTGRES_PASSWORD@db:5432/postgres
export GOTRUE_SITE_URL=$SITE_URL GOTRUE_URI_ALLOW_LIST=$ADDITIONAL_REDIRECT_URLS GOTRUE_MAILER_EXTERNAL_HOSTS=$BOGEY_HOSTS
export GOTRUE_DISABLE_SIGNUP=false GOTRUE_JWT_ADMIN_ROLES=service_role GOTRUE_JWT_AUD=authenticated
export GOTRUE_JWT_DEFAULT_GROUP_NAME=authenticated GOTRUE_JWT_EXP=$JWT_EXPIRY GOTRUE_JWT_SECRET=$JWT_SECRET GOTRUE_JWT_ISSUER=$API_EXTERNAL_URL
export GOTRUE_EXTERNAL_EMAIL_ENABLED=true GOTRUE_EXTERNAL_ANONYMOUS_USERS_ENABLED=false GOTRUE_EXTERNAL_PHONE_ENABLED=false
export GOTRUE_MAILER_AUTOCONFIRM=false GOTRUE_MAILER_OTP_LENGTH=6
export GOTRUE_MAILER_URLPATHS_INVITE=/auth/v1/verify GOTRUE_MAILER_URLPATHS_CONFIRMATION=/auth/v1/verify
export GOTRUE_MAILER_URLPATHS_RECOVERY=/auth/v1/verify GOTRUE_MAILER_URLPATHS_EMAIL_CHANGE=/auth/v1/verify
export GOTRUE_SMTP_ADMIN_EMAIL=${SMTP_FROM:-noreply@localhost} GOTRUE_SMTP_HOST=$SMTP_HOST GOTRUE_SMTP_PORT=${SMTP_PORT:-587}
export GOTRUE_SMTP_USER=$SMTP_USER GOTRUE_SMTP_PASS=$SMTP_PASS GOTRUE_SMTP_SENDER_NAME=${SMTP_SENDER_NAME:-Bogey}
export GOTRUE_HOOK_BEFORE_USER_CREATED_ENABLED=true GOTRUE_HOOK_BEFORE_USER_CREATED_URI=pg-functions://postgres/private/before_user_created
export GOTRUE_HOOK_SEND_EMAIL_ENABLED=true GOTRUE_HOOK_SEND_EMAIL_URI=http://host.docker.internal:3000/api/auth/send-email
export GOTRUE_HOOK_SEND_EMAIL_SECRETS=$SEND_EMAIL_HOOK_SECRET
export GOTRUE_MFA_TOTP_ENROLL_ENABLED=true GOTRUE_MFA_TOTP_VERIFY_ENABLED=true GOTRUE_SECURITY_MANUAL_LINKING_ENABLED=true
for p in GOOGLE GITHUB AZURE GITLAB DISCORD KEYCLOAK; do
  e=${p}_ENABLED i=${p}_CLIENT_ID s=${p}_SECRET u=${p}_URL
  export GOTRUE_EXTERNAL_${p}_ENABLED=${!e:-false} GOTRUE_EXTERNAL_${p}_CLIENT_ID=${!i} GOTRUE_EXTERNAL_${p}_SECRET=${!s}
  export GOTRUE_EXTERNAL_${p}_URL=${!u} GOTRUE_EXTERNAL_${p}_REDIRECT_URI=$API_EXTERNAL_URL/callback
done
export GOTRUE_SAML_ENABLED=${SAML_ENABLED:-false} GOTRUE_SAML_PRIVATE_KEY=$SAML_PRIVATE_KEY
# passkeys as a second factor, for the main host only
export GOTRUE_MFA_WEB_AUTHN_ENROLL_ENABLED=true GOTRUE_MFA_WEB_AUTHN_VERIFY_ENABLED=true
export GOTRUE_WEBAUTHN_RP_ID=$BOGEY_HOST GOTRUE_WEBAUTHN_RP_ORIGINS=$SITE_URL GOTRUE_WEBAUTHN_RP_DISPLAY_NAME=${SMTP_SENDER_NAME:-Bogey}
exec /srv/img/auth/usr/local/bin/auth
