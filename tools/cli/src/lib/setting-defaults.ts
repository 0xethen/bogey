import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { settingDefaults } from "@bogey/config/settings";

export const DEFAULTS_FILE = "04_settings.defaults.gen.sql";

export function settingDefaultsSql(): string {
  const json = JSON.stringify(settingDefaults());
  return `-- Generated by \`bogey db baseline\` from packages/config/src/settings.ts. Do not edit manually.

-- the bottom of every setting's chain: defaults → instance → org → event
create function private.setting_defaults(p_namespace text)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select coalesce($json$${json}$json$::jsonb -> p_namespace, '{}');
$$;
grant execute on function private.setting_defaults(text)
to anon, authenticated, service_role, supabase_auth_admin;
`;
}

export function writeSettingDefaults(root: string): boolean {
  const path = join(root, "supabase", "schemas", DEFAULTS_FILE);
  const sql = settingDefaultsSql();
  if (existsSync(path) && readFileSync(path, "utf-8") === sql) return false;
  writeFileSync(path, sql);
  return true;
}

export function settingDefaultsStale(root: string): boolean {
  const path = join(root, "supabase", "schemas", DEFAULTS_FILE);
  return !existsSync(path) || readFileSync(path, "utf-8") !== settingDefaultsSql();
}
