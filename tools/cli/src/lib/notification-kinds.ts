import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { notificationKindsForSql } from "@bogey/config/notifications";

export const KINDS_FILE = "16_notifications.kinds.gen.sql";

export function notificationKindsSql(): string {
  const json = JSON.stringify(notificationKindsForSql());
  return `-- Generated by \`bogey db baseline\` from packages/config/src/notifications.ts. Do not edit manually.

-- how each core notification kind behaves; null for an extension's kind
create function private.notification_kind(p_kind text)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  select $json$${json}$json$::jsonb -> p_kind;
$$;
revoke execute on function private.notification_kind(text) from anon, authenticated;
`;
}

export function writeNotificationKinds(root: string): boolean {
  const path = join(root, "supabase", "schemas", KINDS_FILE);
  const sql = notificationKindsSql();
  if (existsSync(path) && readFileSync(path, "utf-8") === sql) return false;
  writeFileSync(path, sql);
  return true;
}

export function notificationKindsStale(root: string): boolean {
  const path = join(root, "supabase", "schemas", KINDS_FILE);
  return !existsSync(path) || readFileSync(path, "utf-8") !== notificationKindsSql();
}
