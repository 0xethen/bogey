export const USAGE = `bogey docs [--check]
bogey docs wiki --out <dir> [--repo <owner/name>]

Regenerates the references in docs/reference: settings.md from the settings registry, cli.md from
these commands, notifications.md, windows.md and permissions.md. --check fails when any is stale.

\`wiki\` writes docs/ as GitHub wiki pages into <dir> (a clone of the wiki
repo): one flat page per file, with links between docs pointing at pages and
links to other repo files pointing at GitHub.`;

function describeType(schema: z.ZodType): string {
  const inner = schema instanceof z.ZodOptional ? schema.unwrap() : schema;
  if (inner instanceof z.ZodEnum)
    return inner.options.map((option) => `\`${String(option)}\``).join(" · ");
  if (inner instanceof z.ZodBoolean) return "on / off";
  if (inner instanceof z.ZodNumber) {
    const range = [inner.minValue, inner.maxValue].every((bound) => Number.isFinite(bound))
      ? ` (${inner.minValue} to ${inner.maxValue})`
      : "";
    return `whole number${range}`;
  }
  if (inner instanceof z.ZodArray) return "list";
  if (inner instanceof z.ZodObject) return "group";
  return "text";
}

const INSTANCE_DEFAULTS: Record<string, string> = {
  "branding.name": "`brand.name` in bogey.config.ts",
};

function escapePipes(text: string): string {
  return text.replace(/\\/g, "\\\\").replace(/\|/g, "\\|");
}

function cell(value: unknown): string {
  if (value === undefined) return "—";
  const text = typeof value === "string" ? `\`${value}\`` : `\`${JSON.stringify(value)}\``;
  return escapePipes(text);
}

export function settingsReference(): string {
  const sections = Object.entries(settingsRegistry).map(([namespace, definition]) => {
    const shape: Record<string, z.ZodType> = definition.schema.shape;
    const defaults: Record<string, unknown> = { ...definition.defaults };
    const fields: Record<string, { label: string; description?: string } | undefined> =
      definition.fields ?? {};
    const rows = Object.entries(shape).map(([key, schema]) => {
      const text = schema.description ?? fields[key]?.description ?? fields[key]?.label ?? "";
      const fallback = INSTANCE_DEFAULTS[`${namespace}.${key}`];
      return `| \`${key}\` | ${describeType(schema)} | ${fallback ?? cell(defaults[key])} | ${escapePipes(text)} |`;
    });
    const operator = isCoreNamespace(namespace) ? operatorKeys(namespace) : [];
    return [
      `## ${definition.label} (\`${namespace}\`)`,
      "",
      `Set at: ${definition.scopes.join(", ")}.`,
      ...(operator.length
        ? [
            "",
            `Only the operator sets ${operator.map((key) => `\`${key}\``).join(", ")} for the instance, in [bogey.config.ts](../configuration.md#keys-only-the-file-sets) or with the CLI; admins can't change it in the app.`,
          ]
        : []),
      "",
      "| Key | Type | Default | What it does |",
      "| --- | --- | --- | --- |",
      ...rows,
    ].join("\n");
  });
  return [
    "# Settings reference",
    "",
    "<!-- Generated by `bogey docs` from packages/config/src/settings.ts. Do not edit manually. -->",
    "",
    "Settings live in the database and resolve Bogey's defaults → instance → organization → event;",
    "a level can lock keys for the levels below. Edit them in the app (Instance, Organization and",
    "event pages). See [configuration](../configuration.md) for the other tiers.",
    "",
    ...sections.flatMap((section) => [section, ""]),
  ].join("\n");
}

export function cliReference(commands: Tuple<Command>): string {
  return [
    "# CLI reference",
    "",
    "<!-- Generated by `bogey docs` from tools/cli/src/commands.ts. Do not edit manually. -->",
    "",
    "`bogey` administers an instance: things you can't do from the browser, or shouldn't be able to.",
    "Run it as `bogey <command>` once the alias in [Getting started](../getting-started.md#a-bogey-command) is set, or `vpr bogey <command>` from the repo without it (`bogey` alone opens a menu). In the Docker image it's `bogey` already.",
    "Commands that talk to Supabase read `SUPABASE_URL` and `SUPABASE_SERVICE_ROLE_KEY` from `.env`.",
    "At a terminal, a command asks for what its flags leave out. `--no-input` (or `BOGEY_NO_INPUT=1`) turns that off",
    "for scripts: nothing is asked, and a command that needs an answer says which flag gives it.",
    "",
    "The image carries the CLI too: `docker compose exec web bogey <command>`. It has no checkout, so the",
    "commands that author Bogey (schema, themes, types, release) and the ones that control the host",
    "(`upgrade`, `restart`, `stop`) explain what to do instead. The last column says where each one works.",
    "",
    "| Command | What it does | Works in |",
    "| --- | --- | --- |",
    ...commands.map(
      (command) =>
        `| [\`${command.name}\`](#${command.name}) | ${command.summary} | ${WHERE[command.name] ?? "checkout"} |`,
    ),
    "",
    ...commands.flatMap((command) => [
      `## ${command.name}`,
      "",
      "```",
      withShortFlags(command.usage),
      "```",
      "",
    ]),
  ].join("\n");
}

export function notificationsReference(): string {
  const rows = Object.entries(NOTIFICATION_KINDS).map(([key, kind]) => {
    const channels = [kind.channels.inApp ? "bell" : null, kind.channels.email ? "email" : null]
      .filter(Boolean)
      .join(" and ");
    return `| \`${key}\` | ${kind.label} | ${kind.group} | ${channels || "none"} | ${kind.transactional ? "always sent" : "can be turned off"} | ${escapePipes(kind.description)} |`;
  });
  const emails = Object.entries(EMAIL_KINDS).map(([key, kind]) => {
    const variables = kind.variables.map((variable) => `\`{{${variable.name}}}\``).join(", ");
    return `| \`${key}\` | ${kind.label} | ${variables} | ${escapePipes(kind.description)} |`;
  });
  return [
    "# Notifications and email",
    "",
    "<!-- Generated by `bogey docs` from packages/config/src/notifications.ts and email.ts. Do not edit manually. -->",
    "",
    "Everything Bogey tells people about. Each notification shows in the bell, goes by email, or both; people choose",
    "under Account → Notifications, except for the ones marked *always sent*, which say where they stand.",
    "Plugins add their own as `<plugin>.<kind>`.",
    "",
    "## Notifications",
    "",
    "| Key | Name | Group | Default | Email | What it is |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
    "## Email wording",
    "",
    "Organizers edit the subject and body of each email under Instance, Organization and Event → Email, using these variables.",
    "",
    "| Key | Name | Variables | Sent when |",
    "| --- | --- | --- | --- |",
    ...emails,
    "",
  ].join("\n");
}

