export function permissionsReference(root: string): string {
  const grants = new Map<string, Set<string>>();
  const schemas = join(root, "supabase", "schemas");
  for (const name of readdirSync(schemas).filter((file) => file.endsWith(".sql"))) {
    const sql = readFileSync(join(schemas, name), "utf-8");
    for (const block of sql.matchAll(/insert into public\.role_permissions[^;]*;/g)) {
      for (const [, role, permission] of block[0].matchAll(/\('([^']+)',\s*'([^']+)'\)/g)) {
        if (!role || !permission || role.includes(".")) continue;
        grants.set(permission, (grants.get(permission) ?? new Set()).add(role));
      }
    }
  }
  const roles = ["participant", "staff", "judge"];
  const rows = [...grants.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([permission, held]) =>
        `| \`${permission}\` | ${roles.map((role) => (held.has(role) ? "yes" : "")).join(" | ")} |`,
    );
  return [
    "# Permissions",
    "",
    "<!-- Generated by `bogey docs` from supabase/schemas/*.sql. Do not edit manually. -->",
    "",
    "What each event role may do. The database decides, with these names, in every policy and function; the app only",
    "hides buttons. **Organizers** (and organization admins) can do everything in their event, so they have no column.",
    "Plugins add permissions as `<plugin>.<name>` and roles as `<plugin>.<role>`.",
    "",
    `| Permission | ${roles.map((role) => role[0]!.toUpperCase() + role.slice(1)).join(" | ")} |`,
    `| --- | ${roles.map(() => "---").join(" | ")} |`,
    ...rows,
    "",
  ].join("\n");
}

async function generated(root: string): Promise<Tuple<{ path: string; content: string }>> {
  const { COMMANDS } = await import("../commands.ts");
  return [
    { path: join("docs", "reference", "settings.md"), content: settingsReference() },
    { path: join("docs", "reference", "cli.md"), content: cliReference(COMMANDS) },
    { path: join("docs", "reference", "notifications.md"), content: notificationsReference() },
    { path: join("docs", "reference", "windows.md"), content: windowsReference() },
    { path: join("docs", "reference", "permissions.md"), content: permissionsReference(root) },
  ];
}

function markdownFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return markdownFiles(path);
    return name.endsWith(".md") ? [path] : [];
  });
}

export function pageName(docPath: string): string {
  if (docPath.startsWith("meta/")) return docPath.slice("meta/".length).replace(/\.md$/, "");
  const withoutExt = docPath.replace(/\.md$/, "");
  return withoutExt.replace(/\/README$/, "").replace(/\//g, "-");
}

export function wikiLinks(
  markdown: string,
  docPath: string,
  repo: string,
  repoRoot: string,
): string {
  return markdown.replace(/\]\(([^)\s]+)\)/g, (match, target: string) => {
    if (/^([a-z]+:|#|\/)/i.test(target)) return match;
    const [path = "", anchor] = target.split("#");
    const resolved = posix.normalize(posix.join(posix.dirname(docPath), path));
    const suffix = anchor ? `#${anchor}` : "";
    if (!resolved.startsWith("../") && resolved.endsWith(".md")) {
      return `](${pageName(resolved)}${suffix})`;
    }
    const inRepo = posix.normalize(posix.join("docs", resolved));
    return existsSync(join(repoRoot, inRepo))
      ? `](https://github.com/${repo}/blob/main/${inRepo}${suffix})`
      : match;
  });
}

function writeWiki(root: string, out: string, repo: string): CliResult {
  const docs = join(root, "docs");
  const files = markdownFiles(docs);
  mkdirSync(out, { recursive: true });
  for (const file of files) {
    const docPath = relative(docs, file).split("\\").join("/");
    const content = wikiLinks(readFileSync(file, "utf-8"), docPath, repo, root);
    writeFileSync(join(out, `${pageName(docPath)}.md`), content);
  }
  return { exitCode: 0, output: `Wrote ${files.length} wiki pages to ${out}.` };
}

export async function runDocs(cwd: string, args: string[]): Promise<CliResult> {
  const root = findRepoRoot(cwd);
  if (args[0] === "wiki") {
    const out = args[args.indexOf("--out") + 1];
    if (!args.includes("--out") || !out) return { exitCode: 1, output: USAGE };
    const repoAt = args.indexOf("--repo");
    const repo = (repoAt !== -1 && args[repoAt + 1]) || "0xethen/bogey";
    return writeWiki(root, out, repo);
  }
  if (args.length && !args.includes("--check")) return { exitCode: 1, output: USAGE };

  const stale: string[] = [];
  for (const file of await generated(root)) {
    const path = join(root, file.path);
    const content = file.content;
    const current = existsSync(path) ? readFileSync(path, "utf-8") : "";
    if (current === content) continue;
    stale.push(file.path);
    if (!args.includes("--check")) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
  }
  if (args.includes("--check")) {
    return stale.length
      ? { exitCode: 1, output: `Stale: ${stale.join(", ")}. Run \`bogey docs\`.` }
      : { exitCode: 0, output: "Generated docs are up to date." };
  }
  return {
    exitCode: 0,
    output: stale.length
      ? `Wrote ${stale.join(", ")}.`
      : "Generated docs up to date (nothing changed).",
  };
}
