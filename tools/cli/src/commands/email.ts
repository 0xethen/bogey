import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { DEFAULT_EMAIL_LAYOUT } from "@bogey/utils/email-layout";
import { brand } from "@bogey/config";
import { DEFAULT_EMAIL_TEMPLATES, EMAIL_KINDS, type EmailTemplateKey } from "@bogey/config/email";
import { renderEmail } from "@bogey/utils/email-template";
import { findRepoRoot } from "../lib/repo-root.ts";
import { parseFlags } from "../lib/flags.ts";
import type { CliResult } from "../cli.ts";

export const USAGE = `bogey email templates [--check] [--name <org name>] [--out <folder>]

Bogey's default layout is packages/utils/templates/layout.html. This turns it into
packages/utils/src/layout.gen.ts (what the app and CLI import), then writes
supabase/templates/*.html from the layout and Bogey's default wording, using
GoTrue's own template variables. GoTrue sends these only when Bogey's Send Email
hook isn't set up (local \`supabase start\`, or self-hosted stacks pointing
GOTRUE_MAILER_TEMPLATES_* at them); with the hook, the app renders every email
from the settings instead. --check fails when a file is out of date.

GoTrue doesn't know which org an email is for, so these name one: the instance's
brand name, or --name. --out writes somewhere else (a self-hosted stack's template
folder) and skips the repo's own files and --check.`;

interface Fallback {
  file: string;
  kind: EmailTemplateKey;
  type: string;
}

export const FALLBACK_TEMPLATES: Tuple<Fallback> = [
  { file: "magic_link.html", kind: "signIn", type: "magiclink" },
  { file: "recovery.html", kind: "signIn", type: "recovery" },
  { file: "confirmation.html", kind: "signUp", type: "signup" },
  { file: "invite.html", kind: "invite", type: "invite" },
  { file: "email_change.html", kind: "emailChange", type: "email_change" },
  { file: "reauthentication.html", kind: "reauthentication", type: "reauthentication" },
];

const NOTE =
  "<!-- Generated by `bogey email templates`. Used only when Bogey's send-email hook isn't set up; see docs/self-hosting/email.md. -->\n";

const LAYOUT_SOURCE = ["packages", "utils", "templates", "layout.html"] as const;
const LAYOUT_MODULE = ["packages", "utils", "src", "layout.gen.ts"] as const;

export function layoutPath(root: string): string {
  return join(root, ...LAYOUT_SOURCE);
}

export function layoutModule(layout: string): string {
  return (
    "// Generated by `bogey email templates` from packages/utils/templates/layout.html. Do not edit manually.\n\n" +
    `export const DEFAULT_EMAIL_LAYOUT = ${JSON.stringify(layout)};\n`
  );
}

function syncLayoutModule(root: string, check: boolean): boolean {
  const path = join(root, ...LAYOUT_MODULE);
  const expected = layoutModule(readFileSync(layoutPath(root), "utf-8"));
  const stale = !existsSync(path) || readFileSync(path, "utf-8") !== expected;
  if (stale && !check) writeFileSync(path, expected);
  return stale;
}

export function fallbackHtml(
  template: Fallback,
  name: string = brand.name,
  layout: string = DEFAULT_EMAIL_LAYOUT,
): string {
  const { subject, body } = DEFAULT_EMAIL_TEMPLATES[template.kind];
  const rendered = renderEmail({
    layout,
    fallbackLayout: layout,
    subject,
    body,
    org: name,
    platform: name,
    reason: EMAIL_KINDS[template.kind].reason,
    values: {
      code: "{{ .Token }}",
      link: `{{ .RedirectTo }}?token_hash={{ .TokenHash }}&type=${template.type}`,
      email: "{{ .Email }}",
    },
  });
  return `${NOTE}${rendered.html}`;
}

export function runEmail(cwd: string, args: string[]): CliResult {
  const [subcommand, ...rest] = args;
  if (subcommand !== "templates") return { exitCode: 1, output: USAGE };
  const flags = parseFlags(rest);
  const known = new Set(["check", "name", "out"]);
  const unknown = Object.keys(flags).find((flag) => !known.has(flag));
  if (unknown || rest.some((arg) => !arg.startsWith("--") && !Object.values(flags).includes(arg))) {
    return { exitCode: 1, output: USAGE };
  }
  const name = typeof flags.name === "string" && flags.name.trim() ? flags.name.trim() : brand.name;
  const out = typeof flags.out === "string" ? resolve(cwd, flags.out) : null;
  const root = findRepoRoot(cwd);
  const dir = out ?? join(root, "supabase", "templates");
  const layout = readFileSync(layoutPath(root), "utf-8");
  const layoutStale = out === null && syncLayoutModule(root, flags.check === true);
  const stale = FALLBACK_TEMPLATES.filter((template) => {
    const path = join(dir, template.file);
    return (
      !existsSync(path) || readFileSync(path, "utf-8") !== fallbackHtml(template, name, layout)
    );
  });
  if (flags.check === true && out === null) {
    const outOfDate = [...(layoutStale ? ["layout.gen.ts"] : []), ...stale.map((t) => t.file)];
    return outOfDate.length
      ? {
          exitCode: 1,
          output: `Out of date: ${outOfDate.join(", ")}. Run \`bogey email templates\`.`,
        }
      : { exitCode: 0, output: "The fallback email templates are up to date." };
  }
  mkdirSync(dir, { recursive: true });
  for (const template of stale) {
    writeFileSync(join(dir, template.file), fallbackHtml(template, name, layout));
  }
  return {
    exitCode: 0,
    output: stale.length
      ? `Wrote ${stale.map((template) => template.file).join(", ")}.`
      : "The fallback email templates were already up to date.",
  };
}
