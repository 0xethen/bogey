const HEADER = "// Generated by `bogey types`. Do not edit manually.\n\n";

export const USAGE = `bogey types [--schema [--check] | --mcp <url> | supabase gen types args...]

Regenerates packages/db/src/types/database.gen.ts, keeping only what
supabase/schemas creates (plugin tables are left out). The types describe the
schema files, not a deployment: generate them from any database that has the
current schema (bogey db repair first), and commit them. Production never runs this.

  bogey types                                    DATABASE_URL from .env (or --local without one)
  bogey types --db-url postgres://...              any database you can reach (a dev server,
                                                 a tailnet address; ?sslmode=disable without TLS)
  bogey types --project-id <ref>                 a Supabase Cloud project (SUPABASE_ACCESS_TOKEN)
  bogey types --local                            from \`supabase start\` (needs Docker)
  bogey types --mcp http://localhost:8080/mcp   a self-hosted Studio MCP (SSH tunnel)
  bogey types --schema                           only ${SCHEMA_TYPES_PATH}, which needs no
                                                 database; --check fails when it's stale

Every form also writes ${SCHEMA_TYPES_PATH}: the permissions,
audit actions and checked column values supabase/schemas defines, read from the files.
\`bogey watch --schema\` keeps it current while you edit them.

Needs the Supabase CLI (brew install supabase/tap/supabase); --local and
--db-url run it. The output is laid out with vp fmt before plugin entries are dropped.`;

export interface TypeGenResult {
  error?: Error;
  status: number | null;
  stdout: string;
  stderr: string;
}

export type TypeGenRunner = (args: string[]) => TypeGenResult;

const runSupabase: TypeGenRunner = (args) => {
  const result = spawnSync("supabase", args, { encoding: "utf-8" });
  return {
    error: result.error,
    status: result.status,
    stdout: result.stdout ?? "",
    stderr: result.stderr ?? "",
  };
};

export type McpFetcher = (url: string) => Promise<string>;

export type TypeFormatter = (source: string, root: string) => string;

const formatWithVp: TypeFormatter = (source, root) => {
  const dir = mkdtempSync(join(tmpdir(), "bogey-types-"));
  const file = join(dir, "database.gen.ts");
  try {
    writeFileSync(file, source);
    const result = spawnSync("vp", ["fmt", file], { cwd: root, encoding: "utf-8" });
    return result.status === 0 ? readFileSync(file, "utf-8") : source;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
};

const fetchFromMcp: McpFetcher = async (url) => {
  const response = await fetch(url, {
    method: "POST",
    headers: { "content-type": "application/json", accept: "application/json, text/event-stream" },
    body: JSON.stringify({
      jsonrpc: "2.0",
      id: 1,
      method: "tools/call",
      params: { name: "generate_typescript_types", arguments: {} },
    }),
    signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
  });
  let raw = await response.text();
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  if (raw.startsWith("event:") || raw.startsWith("data:")) {
    raw = raw
      .split("\n")
      .filter((line) => line.startsWith("data:"))
      .map((line) => line.slice(5))
      .join("\n");
  }
  const body = JSON.parse(raw) as { result?: { content?: Array<{ text?: string }> } };
  const text = body.result?.content?.[0]?.text;
  if (!text) throw new Error("the MCP response had no types");
  const decoded: unknown = text.trimStart().startsWith('"') ? JSON.parse(text) : text;
  if (typeof decoded === "string") return decoded;
  if (typeof decoded === "object" && decoded !== null && "types" in decoded) {
    return String((decoded as { types: unknown }).types);
  }
  throw new Error("unexpected MCP response shape");
};

export function keepOnly(source: string, keep: ReadonlySet<string>): string {
  const out: string[] = [];
  let section = "";
  let mode: "keep" | "block" | "tail" = "keep";

  for (const line of source.split("\n")) {
    const indent = line.length - line.trimStart().length;
    if (indent === 2 && line.trimEnd().endsWith("{")) section = line.trim().split(":")[0] ?? "";
    if (mode === "block") {
      if (indent === 6 && /^[}\]]/.test(line.trim())) mode = "keep";
      continue;
    }
    if (mode === "tail") {
      if (indent > 6) continue;
      mode = "keep";
    }
    const name = /^\s{6}(\w+)\??:/.exec(line)?.[1];
    if (section === "public" && indent === 6 && name && !keep.has(name)) {
      mode = /[{[]$/.test(line.trimEnd()) ? "block" : "tail";
      continue;
    }
    out.push(line);
  }
  return out.join("\n");
}

export function coreNames(root: string): Set<string> {
  const dir = join(root, "supabase", "schemas");
  const names = new Set<string>();
  if (!existsSync(dir)) return names;
  for (const file of readdirSync(dir).filter((name) => name.endsWith(".sql"))) {
    const sql = readFileSync(join(dir, file), "utf-8");
    for (const match of sql.matchAll(/create (?:table|view|function|type) public\.(\w+)/g)) {
      names.add(match[1]!);
    }
  }
  return names;
}

export async function runTypes(
  cwd: string,
  args: string[],
  run: TypeGenRunner = runSupabase,
  fetchMcp: McpFetcher = fetchFromMcp,
  format: TypeFormatter = formatWithVp,
  psql: Runner = spawnRunner,
): Promise<CliResult> {
  if (args[0] === "--help") return { exitCode: 0, output: USAGE };

  const root = findRepoRoot(cwd);
  if (args[0] === "--schema") {
    const result = generateSchemaTypes(root, args.includes("--check"));
    return { exitCode: result.ok ? 0 : 1, output: result.output };
  }
  const schemaTypes = generateSchemaTypes(root);
  const outPath = join(root, "packages", "db", "src", "types", "database.gen.ts");
  let generated: string;

  const mcpAt = args.indexOf("--mcp");
  if (mcpAt !== -1) {
    const url = args[mcpAt + 1];
    if (!url) return { exitCode: 1, output: USAGE };
    try {
      generated = await step("Fetch types from the Studio MCP", () => fetchMcp(url));
    } catch (error) {
      return {
        exitCode: 1,
        output: `bogey types: ${error instanceof Error ? error.message : String(error)}`,
      };
    }
  } else {
    const envUrl = args.length === 0 ? databaseUrl(root, undefined) : null;
    if (envUrl) args = ["--db-url", envUrl];
    let result = step("Generate types with supabase gen types", () =>
      run(["gen", "types", "typescript", ...(args.length > 0 ? args : ["--local"])]),
    );
    const noTls = /does not support SSL/.test(`${result.stderr}\n${result.stdout}`);
    if (envUrl && noTls && !/[?&]sslmode=/.test(envUrl)) {
      args = ["--db-url", `${envUrl}${envUrl.includes("?") ? "&" : "?"}sslmode=disable`];
      result = step("Generate types again, without TLS", () =>
        run(["gen", "types", "typescript", ...args]),
      );
    }
    if (result.error) {
      return {
        exitCode: 1,
        output:
          `bogey types: could not run the Supabase CLI (${result.error.message}). ` +
          "Install it (https://supabase.com/docs/guides/local-development/cli/getting-started) or use --mcp.",
      };
    }
    if (result.status !== 0) {
      const said = `${result.stderr}\n${result.stdout}`.trim();
      return {
        exitCode: 1,
        output: [`bogey types: supabase gen types failed\n${said}`.trim()].join("\n"),
      };
    }
    generated = result.stdout;
  }

  const formatted = format(generated, root);
  writeFileSync(outPath, HEADER + keepOnly(formatted, coreNames(root)).trimEnd() + "\n");
  const done = `✓ bogey types: wrote ${outPath} (core schema only)\n${schemaTypes.output}`;

  const dbUrl = args[args.indexOf("--db-url") + 1];
  if (args.includes("--db-url") && dbUrl) {
    const drift = schemaDrift(root, dbUrl, psql);
    if (drift.ok && drift.missing.length > 0) {
      return {
        exitCode: 1,
        output: `${done}\n\n✗ ${describeDrift(drift.missing)}, so these types may be behind. Repair, then run this again.`,
      };
    }
  }
  return { exitCode: 0, output: done };
}
