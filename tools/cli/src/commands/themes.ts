import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { watchInputs } from "../lib/watch-inputs.ts";
import { findRepoRoot } from "../lib/repo-root.ts";
import type { CliResult } from "../cli.ts";

export const USAGE = `bogey themes

Reads packages/ui/src/styles/themes/<key>.theme.css and writes the theme
imports (packages/ui/src/styles/themes.css) and the theme list
(packages/config/src/themes.gen.ts). A file's label comes from a
\`/* @theme Label */\` line; "default" styles :root, others :root[data-theme="<key>"].
\`bogey watch --themes\` keeps them up to date.`;

export interface ThemeFile {
  key: string;
  label: string;
}

const THEME_FILE = /^([a-z][a-z0-9-]*)\.theme\.css$/;

export function readThemes(dir: string): { themes: ThemeFile[]; problems: string[] } {
  const themes: ThemeFile[] = [];
  const problems: string[] = [];
  for (const file of readdirSync(dir).sort()) {
    const key = THEME_FILE.exec(file)?.[1];
    if (!key) continue;
    let css = readFileSync(join(dir, file), "utf-8");
    const label = /\/\*\s*@theme\s+(.+?)\s*\*\//.exec(css)?.[1] ?? key;
    if (key === "default") {
      if (!css.includes(":root {")) problems.push(`${file} should style :root`);
    } else {
      const selector = `:root[data-theme="${key}"]`;
      if (!css.includes(selector)) {
        console.warn(`${file} should style ${selector}, fixing...`);
        css = css
          .replace(/^:root\s*\{/m, `${selector} {`)
          .replace(/^\.dark\s*\{/m, `${selector}.dark {`);
        if (css.includes(selector)) writeFileSync(join(dir, file), css);
        else problems.push(`${file} has no :root block to scope to ${selector}`);
      }
    }
    themes.push({ key, label });
  }
  if (!themes.some((theme) => theme.key === "default"))
    problems.push("default.theme.css is missing");
  themes.sort((a, b) => Number(b.key === "default") - Number(a.key === "default"));
  return { themes, problems };
}

export function themesCss(themes: Tuple<ThemeFile>): string {
  return (
    "/* Generated by `bogey themes` from styles/themes. Do not edit manually. */\n" +
    themes.map((theme) => `@import "themes/${theme.key}.theme.css";\n`).join("")
  );
}

export function themesModule(themes: Tuple<ThemeFile>): string {
  const entries = themes
    .map(
      (theme) =>
        `  { key: ${JSON.stringify(theme.key)}, label: ${JSON.stringify(theme.label)} },\n`,
    )
    .join("");
  return (
    "// Generated by `bogey themes` from packages/ui/src/styles/themes. Do not edit manually.\n\n" +
    `export const THEMES = [\n${entries}] as const;\n\n` +
    'export type ThemeKey = (typeof THEMES)[number]["key"];\n'
  );
}

function writeIfChanged(path: string, content: string): boolean {
  if (existsSync(path) && readFileSync(path, "utf-8") === content) return false;
  writeFileSync(path, content);
  return true;
}

export function generateThemes(root: string): CliResult {
  const dir = join(root, "packages", "ui", "src", "styles", "themes");
  const { themes, problems } = readThemes(dir);
  if (problems.length) {
    return { exitCode: 1, output: `bogey themes:\n${problems.map((p) => `  ${p}`).join("\n")}` };
  }
  const changed = [
    writeIfChanged(join(root, "packages", "ui", "src", "styles", "themes.css"), themesCss(themes)),
    writeIfChanged(join(root, "packages", "config", "src", "themes.gen.ts"), themesModule(themes)),
  ].some(Boolean);
  const list = themes.map((theme) => theme.key).join(", ");
  return { exitCode: 0, output: `bogey themes: ${list}${changed ? " (updated)" : ""}` };
}

export function watchThemes(root: string, log: (line: string) => void): () => void {
  return watchInputs(root, ["packages/ui/src/styles/themes"], () => {
    const result = generateThemes(root);
    if (result.exitCode !== 0 || result.output.endsWith("(updated)")) log(result.output);
  });
}

export function runThemes(cwd: string, args: string[]): CliResult {
  if (args[0] === "--help") return { exitCode: 0, output: USAGE };
  return generateThemes(findRepoRoot(cwd));
}
