create table private.plugin_objects (
  seq bigint generated by default as identity primary key,
  plugin text not null check (plugin ~ '^[a-z][a-z0-9-]{1,30}[a-z0-9]$'),
  kind text not null,
  names text[] not null,
  args text[] not null default '{}',
  identity text not null,
  recorded_at timestamptz not null default now(),
  unique (kind, names, args)
);
create index plugin_objects_plugin_idx on private.plugin_objects (plugin);
revoke all on private.plugin_objects from public, anon, authenticated, service_role;

create function private.plugin_catalog()
returns table (key text, classid oid, objid oid, kind text, identity text, fingerprint text)
language plpgsql
stable
set search_path = ''
as $$
begin
  return query
  with ns as (
    select n.oid from pg_catalog.pg_namespace n
    where n.nspname not in ('pg_catalog', 'information_schema')
      and n.nspname !~ '^pg_(toast|temp_|toast_temp_)'
  ),
  objects (classid, objid, fingerprint) as (
    select 'pg_catalog.pg_namespace'::regclass::oid, n.oid, md5(concat_ws('|', n.nspowner, n.nspacl::text))
    from pg_catalog.pg_namespace n where n.oid in (select oid from ns)
    union all
    select 'pg_catalog.pg_class'::regclass::oid, c.oid, md5(concat_ws('|',
      c.relkind, c.relowner, c.relrowsecurity, c.relforcerowsecurity, c.relreplident, c.relacl::text, c.reloptions::text,
      (select string_agg(concat_ws(':', a.attname, a.atttypid, a.atttypmod, a.attnotnull, a.attisdropped,
          a.attidentity, a.attgenerated, pg_catalog.pg_get_expr(d.adbin, d.adrelid), a.attacl::text), ',' order by a.attnum)
       from pg_catalog.pg_attribute a
       left join pg_catalog.pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
       where a.attrelid = c.oid and a.attnum > 0),
      (select string_agg(con.conname || ' ' || pg_catalog.pg_get_constraintdef(con.oid), ',' order by con.conname)
       from pg_catalog.pg_constraint con where con.conrelid = c.oid),
      case when c.relkind in ('v', 'm') then pg_catalog.pg_get_viewdef(c.oid)
           when c.relkind in ('i', 'I') then pg_catalog.pg_get_indexdef(c.oid) end))
    from pg_catalog.pg_class c
    where c.relnamespace in (select oid from ns) and c.relkind in ('r', 'p', 'v', 'm', 'S', 'f', 'c', 'i', 'I')
    union all
    select 'pg_catalog.pg_proc'::regclass::oid, p.oid, md5(concat_ws('|',
      p.proowner, p.prokind, p.prosecdef, p.provolatile, p.proisstrict, p.proleakproof, p.prorettype,
      p.proargtypes::text, p.prosrc, p.probin, p.proconfig::text, p.proacl::text))
    from pg_catalog.pg_proc p where p.pronamespace in (select oid from ns)
    union all
    select 'pg_catalog.pg_type'::regclass::oid, t.oid, md5(concat_ws('|', t.typowner, t.typacl::text, t.typdefault, t.typnotnull,
      (select string_agg(e.enumlabel, ',' order by e.enumsortorder) from pg_catalog.pg_enum e where e.enumtypid = t.oid),
      (select string_agg(con.conname || ' ' || pg_catalog.pg_get_constraintdef(con.oid), ',' order by con.conname)
       from pg_catalog.pg_constraint con where con.contypid = t.oid)))
    from pg_catalog.pg_type t where t.typnamespace in (select oid from ns) and t.typtype in ('d', 'e', 'r', 'm')
    union all
    select 'pg_catalog.pg_policy'::regclass::oid, po.oid, md5(concat_ws('|', po.polcmd, po.polpermissive, po.polroles::text,
      pg_catalog.pg_get_expr(po.polqual, po.polrelid), pg_catalog.pg_get_expr(po.polwithcheck, po.polrelid)))
    from pg_catalog.pg_policy po
    union all
    select 'pg_catalog.pg_trigger'::regclass::oid, tg.oid, md5(concat_ws('|', tg.tgenabled, pg_catalog.pg_get_triggerdef(tg.oid)))
    from pg_catalog.pg_trigger tg where not tg.tgisinternal
    union all
    select 'pg_catalog.pg_rewrite'::regclass::oid, r.oid, md5(pg_catalog.pg_get_ruledef(r.oid))
    from pg_catalog.pg_rewrite r where r.rulename <> '_RETURN'
    union all
    select 'pg_catalog.pg_publication_rel'::regclass::oid, pr.oid, '' from pg_catalog.pg_publication_rel pr
    union all
    select 'pg_catalog.pg_extension'::regclass::oid, x.oid, x.extversion from pg_catalog.pg_extension x
    union all
    select 'pg_catalog.pg_event_trigger'::regclass::oid, et.oid, md5(concat_ws('|', et.evtevent, et.evtfoid, et.evtenabled))
    from pg_catalog.pg_event_trigger et
  )
  select o.classid::text || ':' || o.objid::text, o.classid, o.objid, i.type, i.identity, o.fingerprint
  from objects o
  cross join lateral pg_catalog.pg_identify_object(o.classid, o.objid, 0) i
  where not exists (
    select 1 from pg_catalog.pg_depend d where d.classid = o.classid and d.objid = o.objid and d.deptype = 'e'
  );

  if pg_catalog.to_regclass('cron.job') is not null then
    return query execute $q$
      select 'cron job:' || j.jobname, null::oid, null::oid, 'cron job', j.jobname::text,
        md5(concat_ws('|', j.schedule, j.command, j.database, j.username, j.active))
      from cron.job j where j.jobname is not null
    $q$;
  end if;
  if pg_catalog.to_regclass('storage.buckets') is not null then
    return query execute $q$
      select 'storage bucket:' || b.id, null::oid, null::oid, 'storage bucket', b.id::text,
        md5(concat_ws('|', b.public, b.file_size_limit, b.allowed_mime_types::text))
      from storage.buckets b
    $q$;
  end if;
end;
$$;

create function private.plugin_recorded()
returns table (key text, plugin text, seq bigint)
language plpgsql
stable
set search_path = ''
as $$
declare
  v_row private.plugin_objects;
  v_classid oid;
  v_objid oid;
begin
  for v_row in select * from private.plugin_objects order by seq loop
    if v_row.kind in ('cron job', 'storage bucket') then
      key := v_row.kind || ':' || v_row.names[1];
    else
      begin
        select a.classid, a.objid into v_classid, v_objid
        from pg_catalog.pg_get_object_address(v_row.kind, v_row.names, v_row.args) a;
      exception when others then
        continue;
      end;
      key := v_classid::text || ':' || v_objid::text;
    end if;
    plugin := v_row.plugin;
    seq := v_row.seq;
    return next;
  end loop;
end;
$$;

create function private.plugin_owners()
returns table (key text, plugin text, seq bigint)
language sql
stable
set search_path = ''
as $$
  with recursive recorded as (
    select * from private.plugin_recorded()
  ),
  tree (classid, objid, plugin) as (
    select split_part(r.key, ':', 1)::oid, split_part(r.key, ':', 2)::oid, r.plugin
    from recorded r where r.key ~ '^\d+:\d+$'
    union
    select d.classid, d.objid, t.plugin
    from pg_catalog.pg_depend d
    join tree t on d.refclassid = t.classid and d.refobjid = t.objid
    where d.deptype in ('a', 'i')
  )
  select r.key, r.plugin, r.seq from recorded r
  union all
  select distinct on (k.key) k.key, k.plugin, null::bigint
  from (select t.classid::text || ':' || t.objid::text as key, t.plugin from tree t) k
  where not exists (select 1 from recorded r where r.key = k.key);
$$;

create function private.plugin_object_name(p_identity text)
returns text
language sql
immutable
set search_path = ''
as $$
  select regexp_replace(regexp_replace(split_part(p_identity, '(', 1), '^.*\.', ''), '"', '', 'g');
$$;

create function private.plugin_migration_begin(p_plugin text)
returns void
language plpgsql
set search_path = ''
as $$
begin
  if p_plugin !~ '^[a-z][a-z0-9-]{1,30}[a-z0-9]$' then
    raise exception 'not a plugin key: %', p_plugin using errcode = '22023';
  end if;
  if current_setting('transaction_isolation') <> 'repeatable read' then
    raise exception 'run a plugin migration in a repeatable read transaction (begin isolation level repeatable read)'
      using errcode = '25000';
  end if;
  if coalesce(current_setting('bogey.plugin_migration', true), '') <> '' then
    raise exception 'a migration of % is still open in this transaction', current_setting('bogey.plugin_migration')
      using errcode = '25000';
  end if;
  perform set_config('bogey.plugin_migration', p_plugin, true);

  create temp table bogey_plugin_before on commit drop as select * from private.plugin_catalog();
  create temp table bogey_plugin_owners on commit drop as select * from private.plugin_owners();
end;
$$;

create function private.plugin_migration_end(
  p_plugin text, p_requires text[] default '{}', p_shared jsonb default '{}'
)
returns void
language plpgsql
set search_path = ''
as $$
declare
  v_problems text[];
begin
  if coalesce(current_setting('bogey.plugin_migration', true), '') is distinct from p_plugin then
    raise exception 'call private.plugin_migration_begin(%) first', quote_literal(p_plugin) using errcode = '25000';
  end if;

  create temp table bogey_plugin_after on commit drop as select * from private.plugin_catalog();

  select array_agg(format('%s %s %s, which belongs to %s',
           case when a.key is null then 'dropped' else 'changed' end, b.kind, b.identity,
           coalesce('the ' || o.plugin || ' plugin', 'Bogey')) order by b.identity)
  into v_problems
  from pg_temp.bogey_plugin_before b
  left join pg_temp.bogey_plugin_after a on a.key = b.key
  left join pg_temp.bogey_plugin_owners o on o.key = b.key
  where (a.key is null or a.fingerprint <> b.fingerprint)
    and o.plugin is distinct from p_plugin;

  create temp table bogey_plugin_added on commit drop as
    select a.* from pg_temp.bogey_plugin_after a
    where not exists (select 1 from pg_temp.bogey_plugin_before b where b.key = a.key);

  v_problems := coalesce(v_problems, '{}') || coalesce((
    select array_agg(format('created extension %s: an instance installs extensions, not a plugin (say what it needs in its README)', x.identity))
    from pg_temp.bogey_plugin_added x where x.kind = 'extension'), '{}');

  create temp table bogey_plugin_tree on commit drop as
    with recursive tree (classid, objid) as (
      select x.classid, x.objid from pg_temp.bogey_plugin_added x where x.classid is not null
      union
      select split_part(o.key, ':', 1)::oid, split_part(o.key, ':', 2)::oid
      from pg_temp.bogey_plugin_owners o where o.plugin = p_plugin and o.key ~ '^\d+:\d+$'
      union
      select d.classid, d.objid
      from pg_catalog.pg_depend d
      join tree t on d.refclassid = t.classid and d.refobjid = t.objid
      where d.deptype in ('a', 'i')
    )
    select t.classid, t.objid, t.classid::text || ':' || t.objid::text as key from tree t;

  create temp table bogey_plugin_dependents on commit drop as
    select t.key from pg_temp.bogey_plugin_tree t
    where exists (
      select 1 from pg_catalog.pg_depend d
      join pg_temp.bogey_plugin_tree p on d.refclassid = p.classid and d.refobjid = p.objid
      where d.classid = t.classid and d.objid = t.objid and d.deptype in ('a', 'i')
    );

  v_problems := v_problems || coalesce((
    select array_agg(distinct format('%s builds on %s of the %s plugin, which %s', i.identity, f.identity, o.plugin,
             case when not o.plugin = any (p_requires) then 'it doesn''t list in `requires`'
                  else 'that plugin doesn''t list in `shares.sql`' end))
    from pg_temp.bogey_plugin_tree t
    join pg_catalog.pg_depend d on d.classid = t.classid and d.objid = t.objid and d.deptype in ('n', 'a')
    join pg_temp.bogey_plugin_owners o on o.key = d.refclassid::text || ':' || d.refobjid::text and o.seq is not null
    join pg_temp.bogey_plugin_after f on f.key = o.key
    cross join lateral pg_catalog.pg_identify_object(t.classid, t.objid, 0) i
    where o.plugin <> p_plugin
      and not (o.plugin = any (p_requires)
               and coalesce(p_shared -> o.plugin, '[]') ? private.plugin_object_name(f.identity))), '{}');

  v_problems := v_problems || coalesce((
    select array_agg(distinct format('%s names %s of the %s plugin, which %s', x.identity, f.identity, o.plugin,
             case when not o.plugin = any (p_requires) then 'it doesn''t list in `requires`'
                  else 'that plugin doesn''t list in `shares.sql`' end))
    from pg_temp.bogey_plugin_after x
    join pg_catalog.pg_proc p on x.classid = 'pg_catalog.pg_proc'::regclass and p.oid = x.objid
    join pg_temp.bogey_plugin_owners o on o.plugin <> p_plugin and o.seq is not null
    join pg_temp.bogey_plugin_after f on f.key = o.key and f.kind in ('table', 'view', 'materialized view', 'function', 'procedure', 'type', 'sequence')
    where (not exists (select 1 from pg_temp.bogey_plugin_before b where b.key = x.key)
           or exists (select 1 from pg_temp.bogey_plugin_before b where b.key = x.key and b.fingerprint <> x.fingerprint))
      and p.prosrc ~* ('\m' || private.plugin_object_name(f.identity) || '\M')
      and not (o.plugin = any (p_requires)
               and coalesce(p_shared -> o.plugin, '[]') ? private.plugin_object_name(f.identity))), '{}');

  if cardinality(v_problems) > 0 then
    raise exception 'the % plugin''s migration can only add to Bogey and change what it made itself:%',
      p_plugin, E'\n  - ' || array_to_string(v_problems, E'\n  - ')
      using errcode = '42501',
            hint = 'Keep the plugin''s data in its own tables, keyed by Bogey''s ids, and its logic in its own functions. See docs/plugins.md#the-database.';
  end if;

  create temp table bogey_plugin_record on commit drop as
    select o.seq, a.key, a.classid, a.objid, a.kind, a.identity
    from pg_temp.bogey_plugin_after a
    left join pg_temp.bogey_plugin_owners o on o.key = a.key and o.plugin = p_plugin and o.seq is not null
    where (o.key is not null)
       or (exists (select 1 from pg_temp.bogey_plugin_added x where x.key = a.key)
           and not exists (select 1 from pg_temp.bogey_plugin_dependents d where d.key = a.key));

  delete from private.plugin_objects where plugin = p_plugin;
  insert into private.plugin_objects (seq, plugin, kind, names, args, identity)
  overriding system value
  select r.seq, p_plugin, r.kind, array[r.identity], '{}', r.identity
  from pg_temp.bogey_plugin_record r where r.classid is null and r.seq is not null;
  insert into private.plugin_objects (seq, plugin, kind, names, args, identity)
  overriding system value
  select r.seq, p_plugin, addr.type, addr.object_names, addr.object_args, r.identity
  from pg_temp.bogey_plugin_record r
  cross join lateral pg_catalog.pg_identify_object_as_address(r.classid, r.objid, 0) addr
  where r.classid is not null and r.seq is not null;
  insert into private.plugin_objects (plugin, kind, names, args, identity)
  select p_plugin, coalesce(addr.type, r.kind), coalesce(addr.object_names, array[r.identity]),
    coalesce(addr.object_args, '{}'), r.identity
  from pg_temp.bogey_plugin_record r
  left join lateral pg_catalog.pg_identify_object_as_address(r.classid, r.objid, 0) addr on r.classid is not null
  where r.seq is null
  order by r.classid is null, r.objid;
  perform setval(pg_catalog.pg_get_serial_sequence('private.plugin_objects', 'seq'),
    greatest((select max(seq) from private.plugin_objects), 1));

  drop table pg_temp.bogey_plugin_before, pg_temp.bogey_plugin_after, pg_temp.bogey_plugin_owners,
    pg_temp.bogey_plugin_added, pg_temp.bogey_plugin_tree, pg_temp.bogey_plugin_dependents, pg_temp.bogey_plugin_record;
  perform set_config('bogey.plugin_migration', '', true);
end;
$$;

create function private.plugin_adopt(p_plugin text, p_objects jsonb)
returns setof text
language plpgsql
set search_path = ''
as $$
declare
  v_item jsonb;
  v_key text;
  v_found record;
begin
  if p_plugin !~ '^[a-z][a-z0-9-]{1,30}[a-z0-9]$' then
    raise exception 'not a plugin key: %', p_plugin using errcode = '22023';
  end if;
  create temp table bogey_adopt_owners on commit drop as select * from private.plugin_owners();
  create temp table bogey_adopt_catalog on commit drop as select * from private.plugin_catalog();

  for v_item in select * from jsonb_array_elements(p_objects) loop
    for v_found in
      select c.* from pg_temp.bogey_adopt_catalog c
      where case v_item ->> 'kind'
        when 'relation' then c.classid = 'pg_catalog.pg_class'::regclass and exists (
          select 1 from pg_catalog.pg_class r where r.oid = c.objid
            and r.relname = v_item ->> 'name' and r.relnamespace::regnamespace::text = v_item ->> 'schema')
        when 'function' then c.classid = 'pg_catalog.pg_proc'::regclass and exists (
          select 1 from pg_catalog.pg_proc p where p.oid = c.objid
            and p.proname = v_item ->> 'name' and p.pronamespace::regnamespace::text = v_item ->> 'schema')
        when 'type' then c.classid = 'pg_catalog.pg_type'::regclass and exists (
          select 1 from pg_catalog.pg_type t where t.oid = c.objid
            and t.typname = v_item ->> 'name' and t.typnamespace::regnamespace::text = v_item ->> 'schema')
        when 'policy' then c.classid = 'pg_catalog.pg_policy'::regclass and exists (
          select 1 from pg_catalog.pg_policy p join pg_catalog.pg_class r on r.oid = p.polrelid
          where p.oid = c.objid and p.polname = v_item ->> 'name' and r.relname = v_item ->> 'table'
            and r.relnamespace::regnamespace::text = v_item ->> 'schema')
        when 'trigger' then c.classid = 'pg_catalog.pg_trigger'::regclass and exists (
          select 1 from pg_catalog.pg_trigger t join pg_catalog.pg_class r on r.oid = t.tgrelid
          where t.oid = c.objid and t.tgname = v_item ->> 'name' and r.relname = v_item ->> 'table'
            and r.relnamespace::regnamespace::text = v_item ->> 'schema')
        when 'publication relation' then c.classid = 'pg_catalog.pg_publication_rel'::regclass and exists (
          select 1 from pg_catalog.pg_publication_rel pr join pg_catalog.pg_class r on r.oid = pr.prrelid
          join pg_catalog.pg_publication pb on pb.oid = pr.prpubid
          where pr.oid = c.objid and pb.pubname = v_item ->> 'name' and r.relname = v_item ->> 'table'
            and r.relnamespace::regnamespace::text = v_item ->> 'schema')
        when 'cron job' then c.key = 'cron job:' || (v_item ->> 'name')
        when 'storage bucket' then c.key = 'storage bucket:' || (v_item ->> 'name')
        when 'schema' then c.classid = 'pg_catalog.pg_namespace'::regclass and c.identity = quote_ident(v_item ->> 'name')
        else false
      end
    loop
      continue when exists (select 1 from pg_temp.bogey_adopt_owners o where o.key = v_found.key);
      continue when v_found.classid is not null and exists (
        select 1 from pg_catalog.pg_depend d
        join pg_temp.bogey_adopt_catalog p on p.classid = d.refclassid and p.objid = d.refobjid
        where d.classid = v_found.classid and d.objid = v_found.objid and d.deptype in ('a', 'i')
          and exists (select 1 from pg_temp.bogey_adopt_owners o where o.key = p.key and o.plugin = p_plugin));
      if v_found.classid is null then
        insert into private.plugin_objects (plugin, kind, names, identity)
        values (p_plugin, v_found.kind, array[v_found.identity], v_found.identity)
        on conflict do nothing;
      else
        insert into private.plugin_objects (plugin, kind, names, args, identity)
        select p_plugin, a.type, a.object_names, a.object_args, v_found.identity
        from pg_catalog.pg_identify_object_as_address(v_found.classid, v_found.objid, 0) a
        on conflict do nothing;
      end if;
      if found then
        insert into pg_temp.bogey_adopt_owners values (v_found.key, p_plugin, null);
        return next v_found.kind || ' ' || v_found.identity;
      end if;
    end loop;
  end loop;
  drop table pg_temp.bogey_adopt_owners, pg_temp.bogey_adopt_catalog;
end;
$$;

create function private.plugin_removal(p_plugin text)
returns table (kind text, identity text, problem text)
language plpgsql
stable
set search_path = ''
as $$
begin
  return query
  with owners as (select * from private.plugin_owners()),
  mine as (select o.key from owners o where o.plugin = p_plugin),
  recorded as (
    select po.seq, po.kind, po.identity, r.key
    from private.plugin_objects po
    left join private.plugin_recorded() r on r.seq = po.seq
    where po.plugin = p_plugin
  )
  select r.kind, r.identity, case when r.key is null then 'already gone' end
  from recorded r
  union all
  select i.type, i.identity, format('depends on %s; it belongs to %s', string_agg(distinct ri.identity, ', '),
           coalesce('the ' || min(o.plugin) || ' plugin', 'Bogey'))
  from pg_catalog.pg_depend d
  cross join lateral pg_catalog.pg_identify_object(d.classid, d.objid, 0) i
  cross join lateral pg_catalog.pg_identify_object(d.refclassid, d.refobjid, 0) ri
  left join owners o on o.key = d.classid::text || ':' || d.objid::text
  where d.refclassid::text || ':' || d.refobjid::text in (select key from mine)
    and d.classid::text || ':' || d.objid::text not in (select key from mine)
    and d.deptype = 'n'
  group by i.type, i.identity;
end;
$$;

create function private.plugin_purge(p_plugin text)
returns setof text
language plpgsql
set search_path = ''
as $$
declare
  v_prefix text := p_plugin || '.';
  v_count bigint;
begin
  if p_plugin !~ '^[a-z][a-z0-9-]{1,30}[a-z0-9]$' then
    raise exception 'not a plugin key: %', p_plugin using errcode = '22023';
  end if;

  delete from public.settings
  where namespace = 'plugin.' || p_plugin or starts_with(namespace, 'plugin.' || v_prefix);
  get diagnostics v_count = row_count;
  if v_count > 0 then return next format('deleted %s settings %s', v_count, case when v_count = 1 then 'row' else 'rows' end); end if;

  update public.settings
  set value = value
    || case when value ? 'enabled' and jsonb_typeof(value -> 'enabled') = 'array'
         then jsonb_build_object('enabled', (value -> 'enabled') - p_plugin) else '{}' end
    || case when value ? 'available' and jsonb_typeof(value -> 'available') = 'array'
         then jsonb_build_object('available', (value -> 'available') - p_plugin) else '{}' end
  where namespace = 'plugins' and (value -> 'enabled' ? p_plugin or value -> 'available' ? p_plugin);
  get diagnostics v_count = row_count;
  if v_count > 0 then return next format('turned it off in %s %s', v_count, case when v_count = 1 then 'org or event' else 'orgs and events' end); end if;

  update public.settings
  set value = jsonb_set(value, '{templates}', coalesce((
    select jsonb_object_agg(t.key, t.value) from jsonb_each(value -> 'templates') t
    where not starts_with(t.key, v_prefix)), '{}'))
  where namespace = 'email' and jsonb_typeof(value -> 'templates') = 'object'
    and exists (select 1 from jsonb_object_keys(value -> 'templates') k where starts_with(k, v_prefix));
  get diagnostics v_count = row_count;
  if v_count > 0 then return next format('deleted its email wording in %s %s', v_count, case when v_count = 1 then 'place' else 'places' end); end if;

  delete from public.roles where source = p_plugin;
  get diagnostics v_count = row_count;
  if v_count > 0 then return next format('deleted %s %s and who had %s', v_count, case when v_count = 1 then 'role' else 'roles' end, case when v_count = 1 then 'it' else 'them' end); end if;

  delete from public.role_permissions where starts_with(permission, v_prefix);
  get diagnostics v_count = row_count;
  if v_count > 0 then return next format('deleted %s %s granted to roles', v_count, case when v_count = 1 then 'permission' else 'permissions' end); end if;

  delete from public.event_windows where starts_with(key, v_prefix);
  get diagnostics v_count = row_count;
  if v_count > 0 then return next format('deleted %s agenda %s', v_count, case when v_count = 1 then 'window' else 'windows' end); end if;

  delete from private.window_states where starts_with(key, v_prefix);

  delete from public.ranking_inputs where starts_with(provider, v_prefix);
  get diagnostics v_count = row_count;
  if v_count > 0 then return next format('deleted %s ranking %s', v_count, case when v_count = 1 then 'score' else 'scores' end); end if;

  delete from public.notifications where starts_with(kind, v_prefix);
  get diagnostics v_count = row_count;
  if v_count > 0 then return next format('deleted %s %s', v_count, case when v_count = 1 then 'notification' else 'notifications' end); end if;

  delete from public.email_outbox where starts_with(kind, v_prefix) and status in ('queued', 'failed');
  get diagnostics v_count = row_count;
  if v_count > 0 then return next format('deleted %s unsent %s', v_count, case when v_count = 1 then 'email' else 'emails' end); end if;

  delete from public.user_preferences where namespace = p_plugin;
  get diagnostics v_count = row_count;
  if v_count > 0 then return next format('deleted %s personal %s', v_count, case when v_count = 1 then 'preference' else 'preferences' end); end if;

  update public.user_preferences
  set value = coalesce((select jsonb_object_agg(c.key, c.value) from jsonb_each(value) c
                        where not starts_with(c.key, v_prefix)), '{}')
  where namespace = 'notifications' and key = 'channels' and jsonb_typeof(value) = 'object'
    and exists (select 1 from jsonb_object_keys(value) k where starts_with(k, v_prefix));

  update public.org_limit_overrides
  set limits = coalesce((select jsonb_object_agg(l.key, l.value) from jsonb_each(limits) l
                         where not starts_with(l.key, v_prefix)), '{}')
  where exists (select 1 from jsonb_object_keys(limits) k where starts_with(k, v_prefix));
  get diagnostics v_count = row_count;
  if v_count > 0 then return next format('cleared limits set for %s %s', v_count, case when v_count = 1 then 'org' else 'orgs' end); end if;
end;
$$;

create function private.plugin_remove(p_plugin text)
returns setof text
language plpgsql
set search_path = ''
as $$
declare
  v_row record;
  v_classid oid;
  v_objid oid;
  v_identity text;
  v_problems text[];
  v_statement text;
begin
  if p_plugin !~ '^[a-z][a-z0-9-]{1,30}[a-z0-9]$' then
    raise exception 'not a plugin key: %', p_plugin using errcode = '22023';
  end if;

  select array_agg(r.identity || ' ' || r.problem) into v_problems
  from private.plugin_removal(p_plugin) r where r.problem is not null and r.problem <> 'already gone';
  if cardinality(v_problems) > 0 then
    raise exception 'the % plugin can''t be removed while something else builds on it:%',
      p_plugin, E'\n  - ' || array_to_string(v_problems, E'\n  - ')
      using errcode = '2BP01', hint = 'Remove the plugins that need it first.';
  end if;

  for v_row in select * from private.plugin_objects where plugin = p_plugin order by seq desc loop
    v_statement := null;
    if v_row.kind = 'cron job' then
      if pg_catalog.to_regclass('cron.job') is not null then
        execute 'select count(*) from cron.job where jobname = $1' into v_objid using v_row.names[1];
        if v_objid > 0 then
          execute 'select cron.unschedule($1)' using v_row.names[1];
          return next 'unscheduled cron job ' || v_row.names[1];
        end if;
      end if;
      continue;
    elsif v_row.kind = 'storage bucket' then
      if pg_catalog.to_regclass('storage.buckets') is not null then
        execute 'select count(*) from storage.objects where bucket_id = $1' into v_objid using v_row.names[1];
        if v_objid > 0 then
          raise exception 'the storage bucket % still holds % files', v_row.names[1], v_objid
            using errcode = '2BP01', hint = 'Empty it through the Storage API (bogey plugins remove does) and try again.';
        end if;
        perform set_config('storage.allow_delete_query', 'true', true);
        execute 'delete from storage.buckets where id = $1' using v_row.names[1];
        perform set_config('storage.allow_delete_query', 'false', true);
        if found then return next 'deleted storage bucket ' || v_row.names[1]; end if;
      end if;
      continue;
    end if;

    begin
      select a.classid, a.objid into v_classid, v_objid
      from pg_catalog.pg_get_object_address(v_row.kind, v_row.names, v_row.args) a;
    exception when others then
      continue;
    end;
    select i.identity into v_identity from pg_catalog.pg_identify_object(v_classid, v_objid, 0) i;
    continue when v_identity is null;

    v_statement := case
      when v_row.kind = 'publication relation' then
        format('alter publication %I drop table %s', v_row.args[1], v_row.names[1] || '.' || v_row.names[2])
      when v_row.kind = 'type' and (select t.typtype from pg_catalog.pg_type t where t.oid = v_objid) = 'd' then
        'drop domain ' || v_identity || ' cascade'
      when v_row.kind = 'composite type' then 'drop type ' || v_identity || ' cascade'
      when v_row.kind in ('table', 'view', 'materialized view', 'sequence', 'index', 'foreign table', 'schema',
                          'function', 'procedure', 'aggregate', 'type', 'policy', 'trigger', 'rule') then
        format('drop %s %s cascade', v_row.kind, v_identity)
    end;
    if v_statement is null then
      raise exception 'don''t know how to remove % %', v_row.kind, v_identity using errcode = '0A000';
    end if;
    execute v_statement;
    return next 'dropped ' || v_row.kind || ' ' || v_identity;
  end loop;

  return query select p.line from private.plugin_purge(p_plugin) p(line);

  delete from private.plugin_objects where plugin = p_plugin;
  if pg_catalog.to_regclass('supabase_migrations.plugin_migrations') is not null then
    execute 'delete from supabase_migrations.plugin_migrations where plugin = $1' using p_plugin;
  end if;
end;
$$;

revoke all on function
